begin;

create table public.products (
  id integer generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 200),
  description text not null,
  price_agorot integer not null check (price_agorot between 1 and 10000000),
  image_path text not null
);

-- The single row permits exactly one explicitly authorized administrator.
create table public.administrators (
  singleton boolean primary key default true check (singleton),
  user_id uuid not null unique references auth.users(id) on delete cascade
);
alter table public.administrators enable row level security;
revoke all on public.administrators from public, anon, authenticated;

create function public.is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists(select 1 from public.administrators where user_id = (select auth.uid())); $$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  product_id integer not null references public.products(id),
  quantity integer not null check (quantity between 1 and 100),
  first_name text not null check (length(btrim(first_name)) between 1 and 200 and first_name = btrim(first_name) and first_name ~ '[^[:space:]]'),
  last_name text not null check (length(btrim(last_name)) between 1 and 200 and last_name = btrim(last_name) and last_name ~ '[^[:space:]]'),
  street_address text not null check (length(btrim(street_address)) between 1 and 200 and street_address = btrim(street_address) and street_address ~ '[^[:space:]]'),
  email text not null check (length(email) <= 254 and email = lower(btrim(email)) and email ~ '^[a-z0-9!#$%&''*+/=?^_`{|}~-]+(\.[a-z0-9!#$%&''*+/=?^_`{|}~-]+)*@gmail\.com$'),
  phone text not null check (phone ~ '^[0-9]{10}$'),
  unit_price_agorot integer not null check (unit_price_agorot between 1 and 10000000),
  total_agorot integer not null check (total_agorot = unit_price_agorot * quantity),
  created_at timestamptz not null default now(),
  status text not null default 'new' check (status in ('new','in_progress','completed'))
);
create index orders_created_at_idx on public.orders(created_at desc);
create index orders_product_id_idx on public.orders(product_id);
alter table public.products enable row level security;
alter table public.orders enable row level security;
revoke all on public.products, public.orders from public, anon, authenticated;
grant select on public.products to anon, authenticated;
create policy products_public_read on public.products for select to anon, authenticated using (true);
grant select on public.orders to authenticated;
grant update(status) on public.orders to authenticated;
create policy orders_admin_read on public.orders for select to authenticated using ((select public.is_admin()));
create policy orders_admin_update on public.orders for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- No direct INSERT privilege exists. This function accepts no price or status.
-- A single transaction reads the current price and writes the snapshot.
create function public.place_order(
  p_product_id integer, p_quantity integer, p_first_name text, p_last_name text,
  p_street_address text, p_email text, p_phone text
) returns uuid language plpgsql security definer set search_path = '' as $$
declare v_price integer; v_id uuid;
begin
  if p_quantity is null or p_quantity < 1 or p_quantity > 100 then
    raise exception 'Invalid quantity' using errcode = '22023';
  end if;
  select price_agorot into v_price from public.products where id = p_product_id for share;
  if not found then raise exception 'Unknown product' using errcode = '22023'; end if;
  insert into public.orders(product_id, quantity, first_name, last_name, street_address, email, phone, unit_price_agorot, total_agorot)
  values (p_product_id, p_quantity, btrim(p_first_name, E' \t\n\r'), btrim(p_last_name, E' \t\n\r'), btrim(p_street_address, E' \t\n\r'), lower(btrim(p_email, E' \t\n\r')), p_phone, v_price, v_price * p_quantity)
  returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.place_order(integer,integer,text,text,text,text,text) from public;
grant execute on function public.place_order(integer,integer,text,text,text,text,text) to anon, authenticated;

